def main():
    by_name = {}
    warn = []
    for lid, seq in LINES_RAW.items():
        for name, x, y in seq:
            if name not in by_name:
                by_name[name] = {"x": x, "y": y, "lines": [lid]}
            else:
                rec = by_name[name]
                if lid not in rec["lines"]:
                    rec["lines"].append(lid)
                d = max(abs(rec["x"] - x), abs(rec["y"] - y))
                if d > 260:
                    warn.append(f"  ! 「{name}」跨线坐标差 {d}px: "
                                f"{rec['lines'][0]}线({rec['x']},{rec['y']}) "
                                f"vs {lid}线({x},{y})")
                else:
                    rec["x"] = round((rec["x"] + x) / 2)
                    rec["y"] = round((rec["y"] + y) / 2)

    stations_out = {}
    for name, rec in by_name.items():
        stations_out[name] = {
            "station_id": name,
            "station_name": name,
            "lines": sorted(rec["lines"], key=lambda v: int(v) if v.isdigit() else 999),
            "x": rec["x"],
            "y": rec["y"],
            "is_transfer": len(rec["lines"]) > 1,
            "open_date": "",
            "description": "",
            "exits": "",
            "facilities": "",
            "landmarks": "",
            "notes": "",
        }

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    with open(OUT_DIR / "stations.json", "w", encoding="utf-8") as f:
        json.dump({
            "version": "2.0",
            "description": "深圳地铁站点数据（8000x8000 坐标系，坐标基于原图分块精读）",
            "stations": stations_out,
        }, f, ensure_ascii=False, indent=2)

    lines_out = []
    for lid, seq in LINES_RAW.items():
        meta = LINE_META[lid]
        seen, order = set(), []
        for name, _x, _y in seq:
            if name in seen:
                continue
            seen.add(name)
            order.append(name)
        lines_out.append({
            "id": lid,
            "name": meta["name"],
            "alias": meta["alias"],
            "color": meta["color"],
            "status": "运营中",
            "order": meta["order"],
            "stations": order,
        })
    lines_out.sort(key=lambda v: v["order"])
    with open(OUT_DIR / "lines.json", "w", encoding="utf-8") as f:
        json.dump({
            "version": "2.0",
            "description": "线路定义。stations 字段为站序（决定地图连线顺序）。",
            "lines": lines_out,
        }, f, ensure_ascii=False, indent=2)

    print(f"[OK] stations.json  {len(stations_out)} 站 "
          f"(换乘 {sum(1 for v in stations_out.values() if v['is_transfer'])})")
    print(f"[OK] lines.json     {len(lines_out)} 条")
    if warn:
        print(f"\n跨线坐标冲突 {len(warn)} 条（同站不同线给出不同坐标）：")
        for w in warn[:30]:
            print(w)


if __name__ == "__main__":
    main()
